#!/usr/bin/env python3
"""Make the shell's greeting picture: Tux in coloured half-block pseudographics next to a
framed info box. Written into the MMU image's rootfs overlay as /etc/profile.d/greeting.sh: a
printf format, embedded in the script, that it fills in (kernel release, available memory,
uptime) at every login shell, on the UART and, through busybox script, on the HDMI text console.

  python3 sw/tools/mkgreeting.py                       # write the overlay's greeting.sh
  python3 sw/tools/mkgreeting.py --preview out.png     # render it as the HDMI console would

The script forks nothing: every fork + exec of busybox costs most of a second on the board's
CPU (a $(cat) for the picture and a $(sed) for the memory cost 2.6 s at each shell start), and
reads as few bytes as it can (busybox's read builtin takes ~1.5 ms per byte there).

Both screens take the same bytes: UTF-8 box-drawing and block characters, which the Linux VT
maps onto the CP437 font (rtl/video/font8x16.hex), and ANSI colours. The VT can show bright
colours (8-15) as foreground only (SGR 100-107 fall back to 40-47), so a character cell, two
pixels of the picture, may hold at most one bright pixel; the white belly is the only bright
colour, and it always sits next to a basic one. The picture has its own blue panel: a black
penguin on the terminal's black background would vanish.
"""
import argparse, os, sys

HERE = os.path.dirname(os.path.abspath(__file__))
REPO = os.path.dirname(os.path.dirname(HERE))
OUT = os.path.join(REPO, "sw/br2-external/board/tang9k-mmu/rootfs-overlay/etc/profile.d/greeting.sh")

# the script around the format; @FORMAT@ is the format, single-quoted
SCRIPT = """\
# The greeting at every login shell: Tux and an info box in pseudographics, on the UART and
# (through busybox script, /usr/bin/console-shell) on the HDMI text console.
# Generated by sw/tools/mkgreeting.py: edit that, not this file.
# Shell built-ins only: a fork + exec costs most of a second on the board. busybox's read
# takes about 1.5 ms per byte there, so only the first 90 bytes of /proc/meminfo (MemAvailable
# is its third 28-byte line). One read per redirection: in this image's busybox (1.38.0) ash, a
# second read from a regular file on the same redirection can block on the terminal.
if [ -t 1 ]; then
	read -r _g_rel < /proc/sys/kernel/osrelease
	read -r _g_up _g_x < /proc/uptime
	read -r -n 90 -d '' _g_x < /proc/meminfo
	_g_x=${_g_x#*MemAvailable:}
	set -- $_g_x
	_g_mem=${1:-?}
	_g_s=${_g_up%.*}
	if [ "$_g_s" -ge 3600 ]; then _g_up="$((_g_s / 3600)) h $((_g_s % 3600 / 60)) min"
	elif [ "$_g_s" -ge 60 ]; then _g_up="$((_g_s / 60)) min $((_g_s % 60)) s"
	else _g_up="$_g_s s"; fi
	printf '@FORMAT@' "$_g_rel" "$_g_mem KB available" "$_g_up"
	unset _g_rel _g_up _g_x _g_mem _g_s
	set --
fi
"""

# Tux, 24 x 24 pixels: two pixel rows per text row. . panel, K black, W white, O orange
TUX = """
........................
.........KKKKKK.........
........KKKKKKKK........
.......KKKKKKKKKK.......
.......KWWWKKWWWK.......
.......KWKWKKWKWK.......
.......KWKWKKWKWK.......
.......KKWOOOOWKK.......
.......KOOOOOOOOK.......
......KKKOOOOOOKKK......
......KKWWWOOWWWKK......
.....KKWWWWWWWWWWKK.....
....KKKWWWWWWWWWWKKK....
...KKKWWWWWWWWWWWWKKK...
..KKKKWWWWWWWWWWWWKKKK..
..KKKKWWWWWWWWWWWWKKKK..
.KKKKWWWWWWWWWWWWWWKKKK.
.KKK.KWWWWWWWWWWWWK.KKK.
.KK..KWWWWWWWWWWWWK..KK.
.....KWWWWWWWWWWWWK.....
...OOOKWWWWWWWWWWKOOO...
..OOOOOKKKKKKKKKKOOOOO..
..OOOOOO........OOOOOO..
........................
""".split()

# letter: (VGA colour, SGR foreground, SGR background or None if the VT can't show it as one)
PIX = {".": (1, "34", "44"), "K": (0, "30", "40"), "W": (15, "97", None), "O": (6, "33", "43")}

# the info box: 50 columns wide; {} marks a value filled in by printf (padded and cut to fit)
BOX_W = 50
B, T, L, V, H = "96", "93", "92", "97", "37"     # border, title, label, value, hint colours
TITLE = "Welcome to Linux on the Tang Nano 9K!"
ROWS = [
    ("top",),
    ("title", TITLE),
    ("sep",),
    ("item", "Board", "Sipeed Tang Nano 9K, Gowin GW1NR-9"),
    ("item", "CPU", "QERV: bit-serial RV32IMA, 42 MHz"),
    ("item", "MMU", "SV32, the kernel in S-mode"),
    ("item", "Kernel", "Linux {}"),
    ("item", "Memory", "8 MB PSRAM, {}"),
    ("item", "Uptime", "{}"),
    ("sep",),
    ("hint", "Try: free, ps, dmesg, cat /proc/cpuinfo"),
    ("bottom",),
]
SAMPLE = ["6.18.7", "2112 KB available", "14 s"]   # for --preview


def sgr(*codes):
    return "\033[" + ";".join(("0",) + codes) + "m"


def tux_rows():
    """The picture as text rows: (characters with SGR codes, visible width)."""
    assert len(TUX) % 2 == 0 and all(len(r) == len(TUX[0]) for r in TUX)
    rows = []
    for y in range(0, len(TUX), 2):
        out, cur = [], None
        for t, b in zip(TUX[y], TUX[y + 1]):
            ft, bt = PIX[t][1:], PIX[b][1:]
            if t == b:
                # a full cell: a space on a basic background, a full block in a bright colour
                ch, st = (" ", (ft[0], ft[1])) if ft[1] else ("█", (ft[0], PIX["."][2]))
            elif bt[1] is None:                       # bright bottom: lower half block
                if ft[1] is None:
                    sys.exit(f"row {y}: two bright pixels in one cell")
                ch, st = "▄", (bt[0], ft[1])
            else:                                     # upper half block on the bottom colour
                ch, st = "▀", (ft[0], bt[1])
            if st != cur:
                out.append(sgr(*st))
                cur = st
            out.append(ch)
        out.append(sgr())
        rows.append(("".join(out), len(TUX[0])))
    return rows


def box_rows():
    inner = BOX_W - 2
    hz = lambda c: c * inner
    rows = []
    for r in ROWS:
        k = r[0]
        if k == "top":
            s = sgr(B) + "╔" + hz("═") + "╗"
        elif k == "bottom":
            s = sgr(B) + "╚" + hz("═") + "╝"
        elif k == "sep":
            s = sgr(B) + "╟" + hz("─") + "╢"
        else:
            if k == "title":
                text = r[1].center(inner)
                body = sgr("1", T) + text
            elif k == "hint":
                text = ("  " + r[1]).ljust(inner)
                body = sgr(H) + text
            else:
                label = f"  {r[1]:<8}"
                width = inner - len(label) - 1
                assert len(r[2]) <= width, r
                if "{}" in r[2]:
                    pre, post = r[2].split("{}")
                    n = width - len(pre) - len(post)
                    value = pre + f"%-{n}.{n}s" + post
                else:
                    value = r[2].ljust(width)
                body = sgr(L) + label + sgr(V) + value + " "
            s = sgr(B) + "║" + body + sgr(B) + "║"
        rows.append(s + sgr())
    return rows


def greeting():
    """The printf format: the picture and the box side by side, centred vertically."""
    art, box = tux_rows(), box_rows()
    n = max(len(art), len(box))
    pad_a = (n - len(art)) // 2
    pad_b = (n - len(box)) // 2
    lines = []
    for i in range(n):
        a = art[i - pad_a][0] if 0 <= i - pad_a < len(art) else " " * len(TUX[0])
        b = box[i - pad_b] if 0 <= i - pad_b < len(box) else ""
        lines.append((a + "  " + b).rstrip())
    text = "\n".join(lines) + "\n"
    assert "\\" not in text and "'" not in text and text.count("%") == text.count("%-")
    return text


# ---------------------------------------------------------------- preview (the HDMI console)
COLOR_TABLE = [0, 4, 2, 6, 1, 5, 3, 7]           # ANSI colour -> VGA, as the Linux VT maps it
VGA = [(0, 0, 0), (0, 0, 170), (0, 170, 0), (0, 170, 170), (170, 0, 0), (170, 0, 170),
       (170, 85, 0), (170, 170, 170), (85, 85, 85), (85, 85, 255), (85, 255, 85),
       (85, 255, 255), (255, 85, 85), (255, 85, 255), (255, 255, 85), (255, 255, 255)]


def preview(text, path, cols=80):
    from PIL import Image
    font = [int(l, 16) for l in open(os.path.join(REPO, "rtl/video/font8x16.hex"))
            if l.strip() and not l.startswith("//")]
    cells, row, col = [[]], 0, 0
    fg, bg, bold = 7, 0, False                   # the VT's default: grey on black
    i = 0
    while i < len(text):
        c = text[i]
        if c == "\033":
            j = text.index("m", i)
            for p in (text[i + 2:j] or "0").split(";"):
                p = int(p)
                if p == 0:
                    fg, bg, bold = 7, 0, False
                elif p == 1:
                    bold = True
                elif p == 22:
                    bold = False
                elif 90 <= p <= 97:
                    bold, fg = True, COLOR_TABLE[p - 90]
                elif 30 <= p <= 37:
                    fg = COLOR_TABLE[p - 30]
                elif 100 <= p <= 107:
                    bg = COLOR_TABLE[p - 100]
                elif 40 <= p <= 47:
                    bg = COLOR_TABLE[p - 40]
            i = j + 1
            continue
        if c == "\n":
            cells.append([])
        else:
            cells[-1].append((c.encode("cp437")[0], fg ^ (8 if bold else 0), bg))
        i += 1
    rows = len(cells)
    img = Image.new("RGB", (cols * 8, rows * 16))
    px = img.load()
    for r, line in enumerate(cells):
        for x, (g, f, b) in enumerate(line[:cols]):
            for gy in range(16):
                bits = font[16 * g + gy]
                for gx in range(8):
                    px[x * 8 + gx, r * 16 + gy] = VGA[f] if bits & (0x80 >> gx) else VGA[b]
    img = img.resize((img.width * 2, img.height * 2), Image.NEAREST)
    img.save(path)


def main():
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--preview", metavar="PNG", help="render it with the HDMI font and palette")
    ap.add_argument("--out", default=OUT)
    a = ap.parse_args()
    text = greeting()
    if a.preview:
        preview(fill(text, SAMPLE), a.preview)
        print(f"wrote {a.preview}")
    else:
        os.makedirs(os.path.dirname(a.out), exist_ok=True)
        with open(a.out, "w", encoding="utf-8") as f:
            f.write(SCRIPT.replace("@FORMAT@", text))
        print(f"wrote {a.out} ({os.path.getsize(a.out)} bytes)")


def fill(fmt, values):
    """printf's %-N.Ns, as busybox does it (byte counts; the values are ASCII)."""
    import re
    it = iter(values)
    return re.sub(r"%-(\d+)\.(\d+)s", lambda m: f"{next(it):<{m.group(1)}.{m.group(2)}}", fmt)


if __name__ == "__main__":
    main()
